stopifnot(identical(req$input,paste0('Document: ',items$text)),identical(sort(response$data$index),0:299))
emb<-do.call(rbind,response$data$embedding)[order(response$data$index),];rownames(emb)<-items$id
stopifnot(nrow(emb)==300,ncol(emb)==1024,all(is.finite(emb)),nrow(unique(emb))==300)
saveRDS(emb,rp('inputs','jina_embeddings.rds'),compress='gzip')
manifest<-data.frame(id=items$id,text=items$text,input=req$input,input_sha256=vapply(req$input,digest::digest,character(1),algo='sha256',serialize=FALSE),model=req$model,dimension=ncol(emb))
wc(manifest,rp('results','processed','embedding_manifest.csv'))
