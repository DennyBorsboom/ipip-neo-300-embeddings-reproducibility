k<-as.data.frame(readxl::read_excel(rp('inputs','IPIP-NEO-ItemKey.xls')))
k<-k[order(k[['Full#']]),];stopifnot(identical(as.integer(k[['Full#']]),1:300))
items<-data.frame(id=sprintf('I%03d',1:300),number=1:300,domain=substr(k$Key,1,1),facet=k$Key,facet_name=k$Facet,key=ifelse(substr(k$Sign,1,1)=='+',1,-1),text=trimws(k$Item))
stopifnot(all(table(items$facet)==10),!anyDuplicated(items$text))
wc(items,rp('inputs','items.csv'))
if(file.exists(rp('inputs','ipip20993.sav'))) {
 dat<-haven::read_sav(rp('inputs','ipip20993.sav'))
 x<-as.matrix(dat[,paste0('i',1:300)])
 saveRDS(x,rp('inputs','source_items_scored.rds'),compress='gzip')
} else x<-readRDS(rp('inputs','source_items_scored.rds'))
stopifnot(ncol(x)==300,nrow(x)==20993,all(is.na(x)|x%in%0:5))
zeros<-sum(x==0,na.rm=TRUE);x[x==0]<-NA
x[,items$key<0]<-6-x[,items$key<0];colnames(x)<-items$id
complete<-complete.cases(x)
saveRDS(x,rp('inputs','responses_administered.rds'),compress='gzip')
saveRDS(x[complete,],rp('results','raw','complete_responses.rds'),compress='gzip')
wc(data.frame(source_row=seq_len(nrow(x)),complete=complete,missing_items=rowSums(is.na(x))),rp('results','processed','inclusion.csv'))
npair<-crossprod(!is.na(x))
wc(data.frame(total=nrow(x),complete=sum(complete),excluded=sum(!complete),missing_responses=zeros,pair_n_min=min(uv(npair)),pair_n_max=max(uv(npair))),rp('results','processed','sample.csv'))
response<-jsonlite::fromJSON(rp('inputs','jina_response.json'))
